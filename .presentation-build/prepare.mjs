import fs from 'node:fs/promises';
import path from 'node:path';
import {pathToFileURL} from 'node:url';
import sharp from 'sharp';
import {chromium} from 'playwright';
const root=path.resolve('..');
const assets=path.resolve('assets');
await fs.mkdir(assets,{recursive:true});
for(const name of ['finora-icon','finora-wordmark']) {
  await sharp(path.join(root,'finora-template/public',name+'.svg'),{density:180}).png().toFile(path.join(assets,name+'.png'));
}
const browser=await chromium.launch({executablePath:'C:/Program Files/Google/Chrome/Application/chrome.exe',headless:true});
const page=await browser.newPage({viewport:{width:1512,height:1100},deviceScaleFactor:2});
await page.goto(pathToFileURL(path.join(root,'finora-template/finora-preview.html')).href);
await page.locator('h1').waitFor();
await page.evaluate(()=>document.fonts.ready);
await page.locator('.stats').screenshot({path:path.join(assets,'summary.png')});
await page.locator('.dashboard-grid').screenshot({path:path.join(assets,'dashboard-detail.png')});
await page.locator('.budget-watch').screenshot({path:path.join(assets,'budget-watch.png')});
await page.getByRole('button',{name:'Transactions',exact:true}).click();
await page.addStyleTag({content:'.topbar{visibility:hidden}'});
const transactionImage=await page.locator('.card').first().screenshot();
const transactionMeta=await sharp(transactionImage).metadata();
const transactionBox=await page.locator('.card').first().boundingBox();
const fourthRow=await page.locator('.card').first().locator('tbody tr').nth(3).boundingBox();
const cropHeight=Math.round((fourthRow.y+fourthRow.height-transactionBox.y)*2);
await sharp(transactionImage).extract({left:0,top:0,width:transactionMeta.width,height:cropHeight}).png().toFile(path.join(assets,'transactions.png'));
await page.getByRole('button',{name:'Monthly report',exact:true}).click();
await page.locator('.report-breakdown').screenshot({path:path.join(assets,'report.png')});
await browser.close();
console.log('Brand assets and prototype screenshots ready.');
